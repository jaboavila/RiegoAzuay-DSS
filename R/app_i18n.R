tr_app <- function(key, language = "es", ...) {
  language <- if (identical(language, "en")) "en" else "es"
  value <- app_dictionary[[language]][[key]]
  if (is.null(value) || is.na(value)) value <- paste0("[", key, "]")
  args <- list(...)
  if (length(args)) do.call(sprintf, c(list(value), args)) else unname(value)
}

translated_choices <- function(keys, values, language = "es") {
  stats::setNames(values, vapply(keys, tr_app, character(1), language = language))
}
